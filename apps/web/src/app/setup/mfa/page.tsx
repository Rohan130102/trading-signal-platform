'use client';

import { useMutation, useQueryClient } from '@tanstack/react-query';
import { Check, Copy } from 'lucide-react';
import { useRouter } from 'next/navigation';
import { type FormEvent, useEffect, useRef, useState } from 'react';
import { AuthFrame } from '@/components/shell/auth-frame';
import { Button, Field, FormError, Input, Loading } from '@/components/ui';
import { api } from '@/lib/api';
import { nextStepPath, useMe } from '@/lib/session';

interface Setup {
  secret: string;
  uri: string;
  qrSvg: string;
}

export default function MfaSetupPage() {
  const router = useRouter();
  const client = useQueryClient();
  const me = useMe();
  const [code, setCode] = useState('');
  const [recovery, setRecovery] = useState<string[] | null>(null);
  const [saved, setSaved] = useState(false);
  const setup = useMutation({ mutationFn: () => api.post<Setup>('/auth/mfa/setup') });
  const enable = useMutation({
    mutationFn: () => api.post<{ recoveryCodes: string[] }>('/auth/mfa/enable', { code }),
    onSuccess: (data) => setRecovery(data.recoveryCodes),
  });
  const started = useRef(false);

  useEffect(() => {
    if (me.isError) router.replace('/login');
    if (!me.data) return;
    if (me.data.next === 'MFA_SETUP' && !started.current) {
      started.current = true;
      setup.mutate();
    } else if (me.data.next !== 'MFA_SETUP' && !recovery) {
      router.replace(nextStepPath(me.data));
    }
  }, [me.data, me.isError, recovery, router, setup]);

  if (recovery) {
    return (
      <AuthFrame
        focused
        title="Save your recovery codes"
        description="If you lose your phone, each of these lets you sign in once. They will not be shown again."
      >
        <ul className="num grid grid-cols-2 gap-2 rounded-xl border border-line bg-surface p-4 text-sm">
          {recovery.map((c) => (
            <li key={c}>{c}</li>
          ))}
        </ul>
        <Button
          className="mt-3 w-full"
          onClick={() => void navigator.clipboard?.writeText(recovery.join('\n')).then(() => setSaved(true))}
        >
          {saved ? <Check className="size-4" aria-hidden /> : <Copy className="size-4" aria-hidden />}
          {saved ? 'Copied' : 'Copy codes'}
        </Button>
        <Button
          variant="primary"
          size="lg"
          className="mt-3 w-full"
          onClick={() => {
            void client.invalidateQueries({ queryKey: ['me'] });
            router.replace('/admin');
          }}
        >
          I have saved them
        </Button>
      </AuthFrame>
    );
  }

  const submit = (event: FormEvent) => {
    event.preventDefault();
    enable.mutate();
  };

  return (
    <AuthFrame
      focused
      title="Set up two-step verification"
      description="Administrator accounts need a code from an authenticator app on your phone."
    >
      {!setup.data && !setup.error && <Loading rows={1} />}
      <FormError error={setup.error} />
      {setup.data && (
        <form onSubmit={submit} className="flex flex-col gap-4">
          <ol className="flex list-decimal flex-col gap-1 pl-5 text-sm text-muted">
            <li>Open your authenticator app and scan this code.</li>
            <li>Type the six digits it shows.</li>
          </ol>
          {/* The SVG comes from our own server, generated by the QR library from a URI we created. */}
          <div
            className="mx-auto w-48 rounded-lg bg-white p-2"
            role="img"
            aria-label="QR code for your authenticator app"
            dangerouslySetInnerHTML={{ __html: setup.data.qrSvg }}
          />
          <details className="text-[13px] text-muted">
            <summary className="cursor-pointer">Cannot scan it? Enter this key instead</summary>
            <code className="num mt-1 block break-all select-all text-text">{setup.data.secret}</code>
          </details>
          <Field label="Six-digit code" error={enable.error ? null : undefined}>
            {(c) => (
              <Input
                {...c}
                className="num tracking-widest"
                inputMode="numeric"
                autoComplete="one-time-code"
                maxLength={6}
                autoFocus
                value={code}
                onChange={(e) => setCode(e.target.value.replace(/\D/g, ''))}
              />
            )}
          </Field>
          <FormError error={enable.error} />
          <Button
            type="submit"
            variant="primary"
            size="lg"
            loading={enable.isPending}
            disabled={code.length !== 6}
            className="w-full"
          >
            Turn on
          </Button>
        </form>
      )}
    </AuthFrame>
  );
}
